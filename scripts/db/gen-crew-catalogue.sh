#!/usr/bin/env bash
# Writes src/lib/crewCatalogue.ts from the agent_catalogue table of a local database built by
# scripts/db/test-local.sh, so the demo store's crew matches the migrations exactly.
# The live store reads the table itself. Re-run after changing the catalogue in a migration.
set -euo pipefail
cd "$(dirname "$0")/../.."
DB="${TEST_DB:-gumption_test}"
json=$(psql -X -At -d "$DB" -c "
  select jsonb_pretty(jsonb_agg(jsonb_build_object(
    'key', key, 'name', name, 'role', role, 'crew_pillar', crew_pillar, 'summary', summary,
    'outcome_metric', outcome_metric, 'model_tier', model_tier, 'job_types', job_types,
    'budget_per_run_credits', budget_per_run_credits, 'budget_per_month_credits', budget_per_month_credits,
    'start_autonomy', start_autonomy, 'entry_paths', entry_paths, 'from_stage', from_stage,
    'min_plan', min_plan, 'minutes_per_outcome', minutes_per_outcome, 'engine', engine,
    'needs', needs, 'sort', sort) order by sort))
  from public.agent_catalogue")
actions=$(psql -X -At -d "$DB" -c "
  select jsonb_pretty(jsonb_agg(to_jsonb(t) order by key)) from public.autonomy_action_types t")
starter=$(psql -X -At -d "$DB" -c "select jsonb_agg(k) from unnest(private.starter_crew()) k")
{
  echo "// Generated by scripts/db/gen-crew-catalogue.sh from the agent_catalogue table. Don't edit by"
  echo "// hand: change the migration, rebuild the local database and run the script again."
  echo "// Used by the demo store; the live store reads the table."
  echo 'import type { ActionType, CatalogueEntry } from "./crew";'
  echo
  echo "export const STARTER_CREW: string[] = ${starter};"
  echo
  echo "export const ACTION_TYPES: ActionType[] = ${actions};"
  echo
  echo "export const CREW_CATALOGUE: CatalogueEntry[] = ${json};"
} > src/lib/crewCatalogue.ts
npx prettier --write src/lib/crewCatalogue.ts > /dev/null
